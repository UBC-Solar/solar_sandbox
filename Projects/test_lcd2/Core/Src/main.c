void init_LCD()
{
  LCD_WriteCommand(0xA0); // ADC select
  LCD_WriteCommand(0xAE); // Display OFF
  LCD_WriteCommand(0xC8); // COM direction scan
  LCD_WriteCommand(0xA2); // LCD bias set
  LCD_WriteCommand(0x2F); // Power Control set
  LCD_WriteCommand(0x26); // Resistor Ratio Set
  LCD_WriteCommand(0x81); // Electronic Volume Command (set contrast) Double Byte: 1 of 2
  LCD_WriteCommand(0x11); // Electronic Volume value (contrast value) Double Byte: 2 of 2
  LCD_WriteCommand(0xAF); // Display ON
}

void ClearLCD(unsigned char *lcd_string)
{
  unsigned int i, j;
  unsigned char page = 0xB0;
  LCD_WriteCommand(0xAE); // Display OFF
  LCD_WriteCommand(0x40); // Display start address + 0x40
  for (i = 0; i < 8; i++)
  {                   // 64 pixel display / 8 pixels per page = 8 pages
    LCD_WriteCommand(page); // send page address
    LCD_WriteCommand(0x10); // column address upper 4 bits + 0x10
    LCD_WriteCommand(0x00); // column address lower 4 bits + 0x00
    for (j = 0; j < 128; j++)
    {                   // 128 columns wide
      LCD_WriteData(0x00); // write clear pixels
      lcd_string++;
    }
    page++; // after 128 columns, go to next page
  }
  LCD_WriteCommand(0xAF);
}

void DispPic(unsigned char *lcd_string)
{
  unsigned int i, j;
  unsigned char page = 0xB0;
  LCD_WriteCommand(0xAE); // Display OFF
  LCD_WriteCommand(0x40); // Display start address + 0x40
  for (i = 0; i < 8; i++)
  {                   // 64 pixel display / 8 pixels per page = 8 pages
    LCD_WriteCommand(page); // send page address
    LCD_WriteCommand(0x10); // column address upper 4 bits + 0x10
    LCD_WriteCommand(0x00); // column address lower 4 bits + 0x00
    for (j = 0; j < 128; j++)
    {                          // 128 columns wide
      LCD_WriteData(*lcd_string); // send picture data
      lcd_string++;
    }
    page++; // after 128 columns, go to next page
  }
  LCD_WriteCommand(0xAF);
}

